func formatRule() config.Rule {
	description := "custom source format"
	limit, tab := 40, 4
	filename, pkg := `[a-z][a-z0-9_]*\.go`, `[a-z][a-z0-9]*`
	return config.Rule{ID: "FMT001", Kind: "source_format", Description: &description, Severity: "error",
		Format: &config.SourceFormat{Packages: []string{"..."}, MaxLineLength: &limit, TabWidth: &tab, FileNamePattern: &filename, PackageNamePattern: &pkg}}
}

func TestLineWidth(t *testing.T) {
	for _, tc := range []struct {
		name, line       string
		limit, tab, want int
	}{
		{"boundary", "abc", 3, 4, 0},
		{"ascii", "abcd", 3, 4, 4},
		{"unicode boundary", "中文a", 3, 4, 0},
		{"unicode byte position", "中文ab", 3, 4, 8},
		{"tab boundary", "a\tb", 5, 4, 0},
		{"tab crossing", "a\tb", 3, 4, 2},
		{"next tab stop", "abcd\tx", 8, 4, 6},
		{"combining codepoints", "e\u0301x", 2, 4, 4},
		{"huge tab", "\t\t", int(^uint(0) >> 1), int(^uint(0) >> 1), 2},
		{"long line", strings.Repeat("x", 100000), 99999, 4, 100000},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if got := firstOverlongColumn(tc.line, tc.limit, tc.tab); got != tc.want {
				t.Fatalf("column=%d, want %d", got, tc.want)
			}
		})
	}
}

func TestSourceFormatDiagnostics(t *testing.T) {
	c := fixture(t)
	c.Rules = []config.Rule{formatRule()}
	body := "//line pretend.go:900\r\npackage Bad_Name\r\n//" + strings.Repeat("中", 39) + "\r\n//" + strings.Repeat("x", 39)
	write(t, c.Project.Root, "odd/BadFile.go", body)
	r, err := Run(context.Background(), c)
	if err != nil {
		t.Fatal(err)
	}
	type finding struct {
		code, file   string
		line, column int
	}
	var got []finding
	for _, d := range r.Diagnostics {
		if d.RuleID != "FMT001" || d.SourcePackage != "example.com/app/odd" || d.Severity != "error" {
			t.Fatalf("%+v", d)
		}
		got = append(got, finding{d.Code, d.File, d.Line, d.Column})
	}
	want := []finding{
		{"invalid_file_name", "odd/BadFile.go", 1, 1},
		{"invalid_package_name", "odd/BadFile.go", 2, 9},
		{"line_too_long", "odd/BadFile.go", 3, 117},
		{"line_too_long", "odd/BadFile.go", 4, 41},
	}
	if !reflect.DeepEqual(got, want) || r.ExitCode() != 1 {
		t.Fatalf("got %+v, want %+v (exit %d)", got, want, r.ExitCode())
	}
	unchanged, err := os.ReadFile(filepath.Join(c.Project.Root, "odd/BadFile.go"))
	if err != nil || string(unchanged) != body {
		t.Fatalf("source modified: %v", err)
	}
	c.Rules[0].Severity = "warning"
	r, err = Run(context.Background(), c)
	if err != nil || r.ExitCode() != 0 || len(r.Diagnostics) != 4 {
		t.Fatalf("warning: %+v %v", r, err)
	}
}

func TestFormatScopeBuildTagsAndCombinedRules(t *testing.T) {
	c := fixture(t)
	f := formatRule()
	f.Format.Packages = []string{"handler/..."}
	*f.Format.MaxLineLength = 0
	*f.Format.FileNamePattern = `a\.go|b\.go|c\.go`
	write(t, c.Project.Root, "handlerkit/Bad.go", "package Bad\n")
	c.Rules[0].Layers[1].Packages = append(c.Rules[0].Layers[1].Packages, "handlerkit")
	// Test files and unselected build tags must not trigger name violations.
	c.Rules = append(c.Rules, f)
	r, err := Run(context.Background(), c)
	if err != nil || len(r.Diagnostics) != 3 {
		t.Fatalf("combined: %+v %v", r, err)
	}
	for _, d := range r.Diagnostics {
		if d.RuleID != "ARCH001" {
			t.Fatalf("scope leaked: %+v", d)
		}
	}
	c.Project.BuildTags = []string{"custom"}
	r, err = Run(context.Background(), c)
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, d := range r.Diagnostics {
		if d.RuleID == "FMT001" && d.File == "handler/tag.go" && d.Code == "invalid_file_name" {
			found = true
		}
	}
	if !found {
		t.Fatalf("tagged source not checked: %+v", r)
	}
	// Fully anchored alternatives must reject a suffix match.
	c.Rules = []config.Rule{f}
	write(t, c.Project.Root, "handler/extra.go", "package handler\n")
	*f.Format.FileNamePattern = `a\.go|b\.go|c\.go|tag\.go|tra\.go`
	r, err = Run(context.Background(), c)
	if err != nil || len(r.Diagnostics) != 1 || r.Diagnostics[0].File != "handler/extra.go" {
		t.Fatalf("full match: %+v %v", r, err)
	}
}

func TestFormatIncludesGeneratedFiles(t *testing.T) {
	c := fixture(t)
	c.Rules = []config.Rule{formatRule()}
	write(t, c.Project.Root, "repo/Generated.go", "// Code generated by test. DO NOT EDIT.\npackage repo\n")
	r, err := Run(context.Background(), c)
	if err != nil || len(r.Diagnostics) != 1 || r.Diagnostics[0].Code != "invalid_file_name" {
		t.Fatalf("generated: %+v %v", r, err)
	}
}
